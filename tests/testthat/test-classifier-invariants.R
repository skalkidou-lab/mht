  expect_false(identical(observed, span_2026("Divigel", 56, "A1", weeks)))
})

test_that("PINNED DEFECT: the minimum-dose loop matches the RAW product name", {
  # The ladder matches the NORMALISED name; the minimum-dose loop matches the
  # RAW one. The two stages disagree about what a product name is.
  #
  # `Progesteron MIC APL` is the witness, and it is a real codebook product.
  # Its raw and normalised forms differ (spaces are stripped), and it reaches
  # the loop: the ladder classifies it C1 on `ProgesteronMICAPL`, then the loop
  # matches the RAW name against the `Progesteron MIC APL` codebook row
  # (3.33 mg/month, min 3 months): floor(10/3.33) = 3 -> 3 * 28 = 84 days.
  #
  # Point the loop at `produkt_clean` and the row stops matching, because
  # `ProgesteronMICAPL` does not contain `Progesteron MIC APL`: the dispensed
  # 10 days survive untouched and the span collapses from 13 weeks to 3.
  weeks <- weeks_between("2015-12-27", "2020-12-27")

  for (nm in names(ladders)) {
    expect_identical(classify(ladders[[nm]], "Progesteron MIC APL"), "C1", info = nm)
