test_that("a prescription whose id is absent from the skeleton reaches nothing", {
  weeks <- weeks_between("2015-01-05", "2016-12-26")
  skeleton <- run_2026(
    data.table::data.table(
      lopnr = c(1L, 99L),
      produkt = "Divigel",
      edatum = as.Date("2015-02-02"),
      fddd = 90
    ),
    ids = 1:2,
    weeks = weeks
  )
  expect_identical(sort(unique(skeleton[A1 == TRUE]$id)), 1L)
})

test_that("a negative or missing fddd drops the row and warns", {
  weeks <- weeks_between("2015-01-05", "2016-12-26")
  for (bad in list(-10, NA_real_)) {
    skeleton <- data.table::CJ(id = 1L, isoyearweek = weeks, sorted = TRUE)
    expect_warning(
      add_lmed_v20250909(
        skeleton,
        data.table::data.table(
          lopnr = 1L,
          produkt = "Divigel",
          edatum = as.Date("2015-02-02"),
          fddd = bad
        ),
        verbose = FALSE
      ),
      "dropped"
    )
    expect_false(any(skeleton$A1))
  }
})

test_that("the caller's lmed keeps its values but gains an index attribute", {
  # The documentation says `lmed` is NOT modified. Its VALUES are not, but the
  # subsetting in the entry point attaches a secondary-index cache to the
  # caller's own object by reference.
  weeks <- weeks_between("2015-01-05", "2016-12-26")
  lmed <- data.table::data.table(
    lopnr = c(1L, 99L),
    produkt = "Divigel",
    edatum = as.Date("2015-02-02"),
    fddd = 90
  )
  before <- data.table::copy(lmed)
  run_2026(lmed, ids = 1:2, weeks = weeks)

  expect_identical(as.data.frame(lmed), as.data.frame(before))
  expect_identical(names(lmed), names(before))
  expect_false("index" %in% names(attributes(before)))
  expect_true("index" %in% names(attributes(lmed)))
})

# -------------------------------------------------------------- normaliser ----

test_that("the normaliser strips spaces and keeps hyphens, in both ladders", {
  # `produkt_clean` is assigned twice; the hyphen-stripping assignment is
  # immediately overwritten by the space-stripping one, so only spaces survive.
  for (nm in names(ladders)) {
    expect_identical(
      normalise(ladders[[nm]], c("Femoston conti", "Femoston-conti", "Mini-Pe")),
      c("Femostonconti", "Femoston-conti", "Mini-Pe"),
      info = nm
    )
  }
})

# ---------------------------------------------------------- ladder / rungs ----

test_that("every ladder pattern classifies to its frozen category, both ladders", {
  # THE PIN. Expected side is the frozen literal, obtained by execution and
  # pasted in. Relabelling ANY rung — `Tibelia` from F1 to B2, say — turns this
  # red, because the expectation does not move with the implementation.
  for (nm in names(ladders)) {
    expect_identical(
      classify(ladders[[nm]], names(FROZEN_PATTERN_CATEGORY)),
      unname(FROZEN_PATTERN_CATEGORY),
      info = nm
    )
  }
})

test_that("every codebook product classifies to its frozen category, both ladders", {
  # THE PIN, over the register-facing spellings rather than the rung literals.
  # Order-insensitive: the codebook's row order is not contractual, so the
  # lookup is by name.
  prods <- workbook_products()
  shared <- intersect(prods, names(FROZEN_PRODUCT_CATEGORY))
  for (nm in names(ladders)) {
    expect_identical(
      classify(ladders[[nm]], shared),
      unname(FROZEN_PRODUCT_CATEGORY[shared]),
      info = nm
    )
  }
})

test_that("the rung sequence matches the frozen declared table, both ladders", {
  # Pins the DECLARED label of every rung, including the three that can never
  # fire, plus the order and the per-pattern multiplicity of the whole ladder.
  #
  # `ladder_rungs()` supplies the OBSERVED-FROM-SOURCE side only. The expected
  # side is the frozen literal, so this is not the vacuous comparison that was
  # removed: relabel a rung and the literal does not move with it.
  for (nm in names(ladders)) {
    r <- ladder_rungs(ladders[[nm]])
    # order and multiplicity
    expect_identical(r$pattern, names(FROZEN_RUNG_DECLARED), info = nm)
    # the declared label of every rung, shadowed ones included
