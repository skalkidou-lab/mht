  skeleton
}

# The only observable of the dispensed duration through an exported entry
# point: the ISO weeks in which the product's category column is TRUE.
#
# THE ANCHOR DATE IS LEAD, NOT PACKAGING, AND ONE ANCHOR IS DIRECTIONAL.
#
# Every duration this file pins is a multiple of 7 (1680, 1008, and n * 28 from
# the minimum-dose loop), so the interval's end lands on the same weekday as
# the anchor. That weekday decides which one-day change is visible, and each
# anchor sees exactly ONE direction. Measured, not reasoned:
#
#            anchor 2016-01-03 (Sun)      anchor 2016-01-04 (Mon)
#   1679          last = 2020-32               last = 2020-32
#   1680          last = 2020-32               last = 2020-33
#   1681          last = 2020-33               last = 2020-33
#
# So the Sunday anchor detects LONGER by one day and is BLIND to shorter; the
# Monday anchor is the mirror image. Two anchors together give one-day
# sensitivity in both directions, and
# "the duration pins detect a one-day change in BOTH directions" runs both.
#
# The default below is the Sunday anchor, so every pin in this file that does
# not name an anchor detects a lengthening and not a shortening.
#
# Two earlier versions of this comment were wrong: the first claimed weekly
# granularity was an inherent limit of the exported surface, the second claimed
# the Sunday anchor gave general one-day sensitivity. Both were written without
# running the shorter case. It is run now, above.
span_2026 <- function(produkt, fddd, category, weeks, anchor = "2016-01-03") {
  skeleton <- run_2026(
    data.table::data.table(
      lopnr = 1L,
      produkt = produkt,
      edatum = as.Date(anchor),
      fddd = fddd
    ),
    ids = 1L,
    weeks = weeks
  )
  w <- skeleton[get(category) == TRUE]$isoyearweek
  list(first = w[1], last = w[length(w)], n = length(w))
}

